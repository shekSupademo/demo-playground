let seq = 0;
const act = (kind: ActivityKind, text: string, daysAgo: number): Activity => ({
  id: `a${++seq}`,
  kind,
  text,
  at: daysFromToday(-daysAgo),
});
const task = (title: string, dueIn: number, done = false): Task => ({
  id: `t${++seq}`,
  title,
  due: daysFromToday(dueIn),
  done,
});
const deal = (
  id: string,
  name: string,
  amount: number,
  stage: DealStage,
  closeIn: number,
): Deal => ({ id, name, amount, stage, close: daysFromToday(closeIn) });

