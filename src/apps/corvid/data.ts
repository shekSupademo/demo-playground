const toIssue =
  (teamId: string, key: string) =>
  ([
    num,
    title,
    statusId,
    priority,
    assigneeId,
    labelIds,
    projectId,
    milestoneId,
    cycleId,
    estimate,
    due,
    updated,
    parent,
  ]: Row): Issue => ({
    id: `${key}-${num}`,
    key: `${key}-${num}`,
    teamId,
    title,
    description: "",
    statusId,
    priority,
    assigneeId,
    labelIds,
    projectId,
    milestoneId,
    cycleId,
    parentId: parent ? `${key}-${parent}` : null,
    estimate,
    due: due === null ? null : daysFromToday(due),
    createdAt: hoursAgo(updated + 24 * 6),
    updatedAt: hoursAgo(updated),
  });

