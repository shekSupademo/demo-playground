export const priceOf = (products: Product[], productId: string) =>
  products.find((p) => p.id === productId)?.price ?? 0;

export const orderSubtotal = (order: Order, products: Product[]) =>
  order.lines.reduce(
    (sum, line) => sum + priceOf(products, line.productId) * line.qty,
    0,
  );

export const orderTotal = (order: Order, products: Product[]) =>
  Math.round((orderSubtotal(order, products) * 1.08 + order.shipping) * 100) /
  100;

