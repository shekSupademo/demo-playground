export const seedCampaigns: Campaign[] = rows.map(
  ([
    id,
    name,
    subject,
    segment,
    status,
    offset,
    time,
    open,
    click,
    unsubscribes,
    author,
  ]) => {
    const recipients =
      status === "Sent" ? Math.round(segmentById(segment).count * 0.985) : 0;
    return {
      id,
      name,
      subject,
      preview: "Freshly roasted and on its way to you",
      segment,
      status,
      date: daysFromToday(offset),
      time,
      recipients,
      opens: Math.round((recipients * open) / 100),
      clicks: Math.round((recipients * click) / 100),
      unsubscribes,
      bounces: status === "Sent" ? Math.round(recipients * 0.006) : 0,
      author,
      body: bodyFor(subject),
    };
  },
);

